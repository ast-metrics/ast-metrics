func requireGit(t *testing.T) {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git is not on PATH")
	}
}

// git runs a git command in dir with a hermetic configuration. date, when not
// empty, sets author and committer dates.
func git(t *testing.T, dir, date string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null"}, args...)...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(),
		"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_SYSTEM=/dev/null",
		"GIT_AUTHOR_NAME=Test", "GIT_AUTHOR_EMAIL=test@example.com",
		"GIT_COMMITTER_NAME=Test", "GIT_COMMITTER_EMAIL=test@example.com",
	)
	if date != "" {
		cmd.Env = append(cmd.Env, "GIT_AUTHOR_DATE="+date, "GIT_COMMITTER_DATE="+date)
	}
	out, err := cmd.CombinedOutput()
	require.NoError(t, err, "git %s: %s", strings.Join(args, " "), out)
	return string(out)
}

func initRepo(t *testing.T) string {
	t.Helper()
	requireGit(t)
	dir := t.TempDir()
	git(t, dir, "", "init", "-q", "-b", "main")
	git(t, dir, "", "config", "user.email", "test@example.com")
	git(t, dir, "", "config", "user.name", "Test")
	return dir
}

func put(t *testing.T, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(rel))
	require.NoError(t, os.MkdirAll(filepath.Dir(p), 0o755))
	require.NoError(t, os.WriteFile(p, []byte(content), 0o644))
}

const simpleProcess = `package svc

func Process(x int) int {
	return x + 1
}
`

const complexProcess = `package svc

func Process(x int) int {
	total := 0
	for i := 0; i < x; i++ {
		if i%2 == 0 {
			total += i
		} else if i%3 == 0 {
			total -= i
		}
		if total > 100 && i > 5 {
			break
		}
		for j := 0; j < i; j++ {
			if j == 3 || j == 4 {
				total++
			}
		}
	}
	if total < 0 {
		return 0
	}
	return total
}
`

const renamedBody = `package util

// Helper doubles a number. This file only moves, its content stays identical.
func Helper(x int) int {
	y := x * 2
	return y + 0
}
`

const generatedBody = `// Code generated by protoc-gen-go. DO NOT EDIT.

package gen

func Generated() int {
	if true {
		return 1
	}
	return 0
}
`

func buildPlanRepo(t *testing.T) string {
	dir := initRepo(t)
	put(t, dir, "go.mod", "module example.com/app\n\ngo 1.21\n")
	put(t, dir, "hub/hub.go", "package hub\n\nfunc Shared() int { return 1 }\n")
	put(t, dir, "a/a.go", "package a\n\nimport \"example.com/app/hub\"\n\nfunc A() int { return hub.Shared() }\n")
	put(t, dir, "b/b.go", "package b\n\nimport \"example.com/app/hub\"\n\nfunc B() int { return hub.Shared() + 1 }\n")
	put(t, dir, "c/c.go", "package c\n\nimport \"example.com/app/hub\"\n\nfunc C() int { return hub.Shared() + 2 }\n")
	put(t, dir, "svc/svc.go", simpleProcess)
	put(t, dir, "svc/svc_test.go", "package svc\n\nimport \"testing\"\n\nfunc TestProcess(t *testing.T) {\n\tif Process(1) != 2 {\n\t\tt.Fatal()\n\t}\n}\n")
	put(t, dir, "old/old.go", "package old\n\nfunc Old() int { return 1 }\n")
	put(t, dir, "util/u.go", renamedBody)
	git(t, dir, "2026-01-01T10:00:00Z", "add", "-A")
	git(t, dir, "2026-01-01T10:00:00Z", "commit", "-q", "-m", "initial")

	git(t, dir, "", "checkout", "-q", "-b", "feature")
	put(t, dir, "svc/svc.go", complexProcess)
	put(t, dir, "new/new.go", "package news\n\nfunc New() int { return 1 }\n")
	git(t, dir, "", "rm", "-q", "old/old.go")
	put(t, dir, "gen/api.go", generatedBody)
	put(t, dir, "README.md", "# App\n")
	git(t, dir, "", "mv", "util/u.go", "util/u2.go")
	git(t, dir, "2026-01-02T10:00:00Z", "add", "-A")
	git(t, dir, "2026-01-02T10:00:00Z", "commit", "-q", "-m", "feat: work")

	// uncommitted modification and untracked file
	put(t, dir, "a/a.go", "package a\n\nimport \"example.com/app/hub\"\n\nfunc A() int { return hub.Shared() * 2 }\n")
	put(t, dir, "scratch.go", "package scratch\n\nfunc S() int { return 3 }\n")
	return dir
}

func skippedKind(plan *Plan, path string) (string, bool) {
	for _, s := range plan.Skipped {
		if s.Path == path {
			return s.Kind, true
		}
	}
	return "", false
}

func fileByPath(plan *Plan, path string) *FileReport {
	for i := range plan.Files {
		if plan.Files[i].Path == path {
			return &plan.Files[i]
		}
	}
	return nil
}

func TestRunEndToEnd(t *testing.T) {
	dir := buildPlanRepo(t)
	repo, err := OpenRepo(dir)
	require.NoError(t, err)
	now := time.Date(2026, 1, 10, 0, 0, 0, 0, time.UTC)
	opts := Options{Base: "main", Top: 3, Clones: true, Now: now}

	plan, err := Run(repo, opts)
	require.NoError(t, err)

	// svc.go, new.go, gen/api.go, README.md, old.go (D), util/u2.go (R), a.go, scratch.go
	assert.Equal(t, 8, plan.Changed)
	assert.Equal(t, MethodologyVersion, plan.Methodology)
	assert.Equal(t, "main", plan.Base)
	assert.NotEmpty(t, plan.HeadSha)
	assert.False(t, plan.Calibrated)

	// code files: svc.go, new.go, a.go, scratch.go
	var codePaths []string
	for _, f := range plan.Files {
		codePaths = append(codePaths, f.Path)
	}
	assert.ElementsMatch(t, []string{"svc/svc.go", "new/new.go", "a/a.go", "scratch.go"}, codePaths)
	assert.Equal(t, 3, plan.ReadCount)

	svc := fileByPath(plan, "svc/svc.go")
	require.NotNil(t, svc)
	assert.True(t, svc.Read)
	idx := -1
	for i, f := range plan.Files {
		if f.Path == "svc/svc.go" {
			idx = i
		}
	}
	assert.LessOrEqual(t, idx, 1, "complexity-grown file is ranked first or second")
	assert.Greater(t, svc.Values[FeatureComplexityAdded], 5.0)
	require.NotEmpty(t, svc.Functions)
	assert.False(t, svc.Functions[0].New)
	assert.Greater(t, svc.Functions[0].After, svc.Functions[0].Before)

	for _, f := range plan.Files {
		if f.Read {
			assert.NotEmpty(t, f.Reasons, f.Path)
		}
	}
	// only the three read files carry Read = true
	reads := 0
	for _, f := range plan.Files {
		if f.Read {
			reads++
		}
	}
	assert.Equal(t, plan.ReadCount, reads)

	for path, kind := range map[string]string{
		"old/old.go": "deleted",
		"README.md":  "not analyzed",
		"gen/api.go": "generated",
		"util/u2.go": "renamed",
	} {
		got, ok := skippedKind(plan, path)
		assert.True(t, ok, path)
		assert.Equal(t, kind, got, path)
	}
	// the code file that did not make the list is skipped as "code"
	for _, f := range plan.Files {
		if !f.Read {
			kind, ok := skippedKind(plan, f.Path)
			assert.True(t, ok)
			assert.Equal(t, "code", kind)
		}
	}
	nonCode := 0
	for _, s := range plan.Skipped {
		if s.Kind != "code" {
			nonCode++
		}
	}
	assert.Equal(t, plan.Changed, len(plan.Files)+nonCode)
	assert.Equal(t, 0, plan.TestFiles)

	// renders
	assert.Contains(t, plan.Markdown(), "## Cribelo: read 3 of 8 changed files")
	assert.Contains(t, plan.Text(), "Start with svc/svc.go:")
	js, err := plan.JSON()
	require.NoError(t, err)
	assert.True(t, json.Valid([]byte(js)))

	explained, err := plan.Explain("svc/svc.go")
	require.NoError(t, err)
	assert.Contains(t, explained, "svc/svc.go")
	assert.Contains(t, explained, "Process")
	_, err = plan.Explain("does/not/exist.go")
	assert.Error(t, err)

	// gate
	for _, failOn := range []string{"high", "medium", "never"} {
		o := opts
		o.FailOn = failOn
		p, err := Run(repo, o)
		require.NoError(t, err)
		assert.Contains(t, []string{"passed", "failed"}, p.Gate)
		switch failOn {
		case "high":
			assert.Equal(t, p.Count(LevelHigh) > 0, p.Gate == "failed")
		case "medium":
			assert.Equal(t, p.Count(LevelHigh)+p.Count(LevelMedium) > 0, p.Gate == "failed")
		default:
			assert.Equal(t, "passed", p.Gate)
		}
	}

	// determinism
	again, err := Run(repo, opts)
	require.NoError(t, err)
	againJS, err := again.JSON()
	require.NoError(t, err)
	assert.Equal(t, js, againJS)
}

func TestRunNothingChanged(t *testing.T) {
	dir := initRepo(t)
	put(t, dir, "a.go", "package a\n")
	git(t, dir, "", "add", "-A")
	git(t, dir, "", "commit", "-q", "-m", "init")
	repo, err := OpenRepo(dir)
	require.NoError(t, err)
	plan, err := Run(repo, Options{Base: "main"})
	require.NoError(t, err)
	assert.Equal(t, 0, plan.Changed)
	assert.Equal(t, "passed", plan.Gate)
	assert.Contains(t, plan.Text(), "Nothing changed")
}

func TestRunUsesConfigIgnoreAndErrors(t *testing.T) {
	dir := buildPlanRepo(t)
	put(t, dir, ConfigFile, "ignore:\n  - svc/**\n  - README.md\n")
	repo, err := OpenRepo(dir)
	require.NoError(t, err)
	plan, err := Run(repo, Options{Base: "main", Now: time.Date(2026, 1, 10, 0, 0, 0, 0, time.UTC)})
	require.NoError(t, err)
	assert.Nil(t, fileByPath(plan, "svc/svc.go"))
	_, skipped := skippedKind(plan, "README.md")
	assert.False(t, skipped, "ignored files are neither ranked nor listed")
	// .cribelo.yaml itself is untracked and not analyzed
	kind, ok := skippedKind(plan, ConfigFile)
	assert.True(t, ok)
	assert.Equal(t, "not analyzed", kind)

	_, err = Run(repo, Options{Base: "no-such-branch"})
	assert.Error(t, err)
}

func TestOpenRepoErrorAndRefs(t *testing.T) {
	requireGit(t)
	_, err := OpenRepo(t.TempDir())
	assert.Error(t, err)

	dir := buildPlanRepo(t)
	repo, err := OpenRepo(filepath.Join(dir, "svc"))
	require.NoError(t, err)
	assert.Equal(t, canonical(t, dir), canonical(t, repo.Root))
	base, err := repo.DefaultBranch()
	require.NoError(t, err)
	assert.Equal(t, "main", base)
	_, err = repo.ResolveRef("nope")
	assert.Error(t, err)
	sha, err := repo.ResolveRef("main")
	require.NoError(t, err)
	assert.Len(t, sha, 40)
	tm, err := repo.CommitTime(sha)
	require.NoError(t, err)
	assert.Equal(t, time.Date(2026, 1, 1, 10, 0, 0, 0, time.UTC).Unix(), tm)
	files, err := repo.TreeFiles()
	require.NoError(t, err)
	assert.Contains(t, files, "scratch.go", "untracked files are included")
	assert.Contains(t, files, "util/u2.go")
	assert.NotContains(t, files, "old/old.go")
	data, err := repo.Show(sha, "old/old.go")
	require.NoError(t, err)
	assert.Contains(t, string(data), "package old")
	_, err = repo.Show(sha, "missing.go")
	assert.Error(t, err)
}

func canonical(t *testing.T, p string) string {
	t.Helper()
	r, err := filepath.EvalSymlinks(p)
	require.NoError(t, err)
	return r
}

func TestChangesAgainstRealGit(t *testing.T) {
	dir := buildPlanRepo(t)
	repo, err := OpenRepo(dir)
	require.NoError(t, err)
	changes, err := repo.Changes("main", "")
	require.NoError(t, err)
	byPath := map[string]Change{}
	for _, c := range changes {
		byPath[c.Path] = c
	}
	assert.Len(t, changes, 8)
	assert.Equal(t, byte('D'), byPath["old/old.go"].Status)
	assert.Equal(t, byte('A'), byPath["new/new.go"].Status)
	assert.Equal(t, byte('R'), byPath["util/u2.go"].Status)
	assert.Equal(t, "util/u.go", byPath["util/u2.go"].OldPath)
	assert.Equal(t, 0, byPath["util/u2.go"].Added)
	assert.True(t, byPath["scratch.go"].Untracked)
	assert.Equal(t, 3, byPath["scratch.go"].Added)
	assert.Equal(t, []Hunk{{1, 3}}, byPath["scratch.go"].Hunks)
	assert.Equal(t, byte('M'), byPath["a/a.go"].Status)
	assert.Equal(t, 1, byPath["a/a.go"].Added)
	assert.Equal(t, 1, byPath["a/a.go"].Deleted)
	assert.Equal(t, []Hunk{{5, 5}}, byPath["a/a.go"].Hunks)
	assert.Greater(t, byPath["svc/svc.go"].Added, 10)
	// sorted by path
	for i := 1; i < len(changes); i++ {
		assert.Less(t, changes[i-1].Path, changes[i].Path)
	}
	// committed range only: no untracked file, no working tree edit
	committed, err := repo.Changes("main", "HEAD")
	require.NoError(t, err)
	assert.Len(t, committed, 6)
}

func TestHistoryAndLandingsRealGit(t *testing.T) {
	dir := buildPlanRepo(t)
	repo, _ := OpenRepo(dir)
	h, err := repo.History("HEAD")
	require.NoError(t, err)
	commits, _ := h.Before("svc/svc.go", time.Date(2026, 1, 10, 0, 0, 0, 0, time.UTC).Unix(), Window)
	assert.Equal(t, 2, commits)

	landings, err := repo.Landings("HEAD", 10, 0)
	require.NoError(t, err)
	require.Len(t, landings, 1, "the root commit is left out")
	older, err := repo.Landings("HEAD", 10, landings[0].Time-1)
	require.NoError(t, err)
	assert.Empty(t, older, "before keeps only commits at least that old")
	older, err = repo.Landings("HEAD", 10, landings[0].Time)
	require.NoError(t, err)
	require.Len(t, older, 1)
	assert.Equal(t, "feat: work", landings[0].Subject)
	assert.False(t, landings[0].Merge)
	assert.Equal(t, repo.MergeBase("main", "HEAD"), landings[0].Parent)
	assert.Equal(t, "xyz", repo.MergeBase("xyz", "also-bad"), "falls back to the first argument")
}
