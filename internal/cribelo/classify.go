package cribelo

import (
	"path"
	"regexp"
	"strings"
)

// Kind says what a changed file is, and therefore whether it can be ranked.
// Only KindCode files are scored; the others are listed as skipped.
type Kind int

const (
	KindCode Kind = iota
	KindTest
	KindGenerated
	KindRenamed
	KindDeleted
	KindBinary
	KindNotAnalyzed
)

func (k Kind) String() string {
	switch k {
	case KindCode:
		return "code"
	case KindTest:
		return "tests"
	case KindGenerated:
		return "generated"
	case KindRenamed:
		return "renamed"
	case KindDeleted:
		return "deleted"
	case KindBinary:
		return "binary"
	default:
		return "not analyzed"
	}
}

// Label is the wording of a skip category in reports.
func (k Kind) Label() string {
	switch k {
	case KindTest:
		return "tests only"
	case KindGenerated:
		return "generated"
	case KindRenamed:
		return "renamed, unchanged"
	case KindDeleted:
		return "deleted"
	case KindBinary:
		return "binary"
	default:
		return "not analyzed (docs, config, other languages)"
	}
}

// analyzedExtensions are the languages the engines parse.
var analyzedExtensions = map[string]bool{
	".go": true, ".php": true, ".py": true, ".rs": true,
	".ts": true, ".tsx": true, ".java": true, ".cs": true,
}

var generatedPathPatterns = []string{
	"vendor/", "third-party/", "third_party/", "node_modules/", "/dist/", "/build/", "__snapshots__/",
	".pb.go", "_generated.", ".generated.", ".gen.go", ".min.js", ".min.css", ".d.ts",
	"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "composer.lock", "Cargo.lock", "go.sum", "Gemfile.lock", "poetry.lock",
}

var generatedHeaderPattern = regexp.MustCompile(`(?i)(code generated[^\n]*do not edit|@generated|auto-?generated|generated by |do not (edit|modify) (this|by hand))`)

var testPathPatterns = []string{
	"_test.go", "Test.php", "Tests.php", "_test.py", ".test.ts", ".spec.ts", ".test.tsx", ".spec.tsx",
	"Test.java", "Tests.java", "IT.java", "Test.cs", "Tests.cs", "_test.rs",
}

// IsTestPath guesses from the path alone whether a file holds tests. The
// parsed file is more precise; this is the fallback when it is unavailable.
func IsTestPath(p string) bool {
	base := path.Base(p)
	for _, suffix := range testPathPatterns {
		if strings.HasSuffix(base, suffix) {
			return true
		}
	}
	if strings.HasPrefix(base, "test_") && strings.HasSuffix(base, ".py") {
		return true
	}
	slashed := "/" + p
	for _, dir := range []string{"/tests/", "/test/", "/__tests__/", "/spec/", "/testdata/"} {
		if strings.Contains(slashed, dir) {
			return true
		}
	}
	return false
}

// IsGeneratedPath reports whether the path alone marks a file as generated.
func IsGeneratedPath(p string) bool {
	slashed := "/" + p
	for _, pattern := range generatedPathPatterns {
		if strings.Contains(slashed, pattern) {
			return true
		}
	}
	return false
}

// IsGeneratedContent looks for a generation marker in the comment lines of
// the first kilobyte of a file. Only comment lines count: a file that merely
// mentions such a marker in its code (a tool that detects them, say) is not
// generated.
func IsGeneratedContent(content []byte) bool {
	if len(content) > 1024 {
		content = content[:1024]
	}
	for _, line := range strings.Split(string(content), "\n") {
		trimmed := strings.TrimSpace(line)
		if isCommentLine(trimmed) && generatedHeaderPattern.MatchString(trimmed) {
			return true
		}
	}
	return false
}

var commentMarkers = []string{"//", "#", "/*", "*", "--", "<!--", "'''", `"""`}

func isCommentLine(line string) bool {
	for _, marker := range commentMarkers {
		if strings.HasPrefix(line, marker) {
			return true
		}
	}
	return false
}

// Classify decides the kind of a change. content is the head version of the
// file (nil when unavailable); isTest comes from the parsed file when known.
func Classify(c Change, content []byte, isTest bool) Kind {
	switch {
	case c.Status == 'D':
		return KindDeleted
	case c.Binary:
		return KindBinary
	case c.Status == 'R' && c.Added == 0 && c.Deleted == 0:
		return KindRenamed
	}
	if !analyzedExtensions[strings.ToLower(path.Ext(c.Path))] {
		return KindNotAnalyzed
	}
	if IsGeneratedPath(c.Path) || IsGeneratedContent(content) {
		return KindGenerated
	}
	if isTest || IsTestPath(c.Path) {
		return KindTest
	}
	return KindCode
}
