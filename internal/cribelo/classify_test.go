func TestKindStringAndLabel(t *testing.T) {
	kinds := map[Kind][2]string{
		KindCode:        {"code", "not analyzed (docs, config, other languages)"},
		KindTest:        {"tests", "tests only"},
		KindGenerated:   {"generated", "generated"},
		KindRenamed:     {"renamed", "renamed, unchanged"},
		KindDeleted:     {"deleted", "deleted"},
		KindBinary:      {"binary", "binary"},
		KindNotAnalyzed: {"not analyzed", "not analyzed (docs, config, other languages)"},
	}
	for k, want := range kinds {
		assert.Equal(t, want[0], k.String())
		assert.Equal(t, want[1], k.Label())
	}
}

func TestClassify(t *testing.T) {
	goGen := []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n")
	pyGen := []byte("# @generated\nx = 1\n")
	notGen := []byte("package x\n\nvar x = \"DO NOT EDIT\"\n")
	tests := []struct {
		name    string
		change  Change
		content []byte
		isTest  bool
		want    Kind
	}{
		{"deleted", Change{Path: "a.go", Status: 'D'}, nil, false, KindDeleted},
		{"deleted wins over binary", Change{Path: "a.go", Status: 'D', Binary: true}, nil, false, KindDeleted},
		{"binary", Change{Path: "a.go", Status: 'M', Binary: true}, nil, false, KindBinary},
		{"pure rename", Change{Path: "b.go", OldPath: "a.go", Status: 'R'}, nil, false, KindRenamed},
		{"pure rename of markdown", Change{Path: "b.md", OldPath: "a.md", Status: 'R'}, nil, false, KindRenamed},
		{"rename with edit", Change{Path: "b.go", OldPath: "a.go", Status: 'R', Added: 1}, nil, false, KindCode},
		{"markdown", Change{Path: "README.md", Status: 'M', Added: 3}, nil, false, KindNotAnalyzed},
		{"javascript", Change{Path: "x.js", Status: 'M', Added: 3}, nil, false, KindNotAnalyzed},
		{"uppercase extension", Change{Path: "X.GO", Status: 'M', Added: 3}, nil, false, KindCode},
		{"vendor path", Change{Path: "vendor/x/y.go", Status: 'M', Added: 1}, nil, false, KindGenerated},
		{"pb.go", Change{Path: "api/x.pb.go", Status: 'M', Added: 1}, nil, false, KindGenerated},
		{"lock file not analyzed", Change{Path: "package-lock.json", Status: 'M', Added: 1}, nil, false, KindNotAnalyzed},
		{"d.ts", Change{Path: "types/x.d.ts", Status: 'M', Added: 1}, nil, false, KindGenerated},
		{"go header", Change{Path: "x.go", Status: 'M', Added: 1}, goGen, false, KindGenerated},
		{"python header", Change{Path: "x.py", Status: 'M', Added: 1}, pyGen, false, KindGenerated},
		{"marker in code line", Change{Path: "x.go", Status: 'M', Added: 1}, notGen, false, KindCode},
		{"isTest flag", Change{Path: "x.go", Status: 'M', Added: 1}, nil, true, KindTest},
		{"test by path go", Change{Path: "x_test.go", Status: 'M', Added: 1}, nil, false, KindTest},
		{"test by path py", Change{Path: "pkg/test_x.py", Status: 'M', Added: 1}, nil, false, KindTest},
		{"test by dir", Change{Path: "src/__tests__/a.ts", Status: 'M', Added: 1}, nil, false, KindTest},
		{"generated wins over test", Change{Path: "vendor/x_test.go", Status: 'M', Added: 1}, nil, true, KindGenerated},
		{"code", Change{Path: "internal/x.go", Status: 'M', Added: 1}, nil, false, KindCode},
		{"added code", Change{Path: "x.php", Status: 'A', Added: 5}, nil, false, KindCode},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, Classify(tt.change, tt.content, tt.isTest))
		})
	}
}

func TestIsTestPath(t *testing.T) {
	for _, p := range []string{"a_test.go", "x/SessionTest.php", "x/FooTests.cs", "a/b/test_token.py", "a/token_test.py",
		"a.spec.ts", "a.test.tsx", "src/FooIT.java", "tests/helper.go", "pkg/testdata/x.go", "src/__tests__/a.ts", "spec/x.rs", "lib/a_test.rs"} {
		assert.True(t, IsTestPath(p), p)
	}
	for _, p := range []string{"a.go", "latest/x.go", "contest.go", "test_x.go", "src/protest.ts"} {
		assert.False(t, IsTestPath(p), p)
	}
}

func TestIsGeneratedPath(t *testing.T) {
	for _, p := range []string{"vendor/a.go", "pkg/vendor/a.go", "node_modules/x/y.ts", "web/dist/a.ts", "x/build/y.go",
		"a/__snapshots__/b.ts", "api/x.pb.go", "x_generated.go", "x.generated.ts", "x.gen.go", "a.min.js", "go.sum", "sub/Cargo.lock"} {
		assert.True(t, IsGeneratedPath(p), p)
	}
	for _, p := range []string{"main.go", "src/distribution.go", "builder/x.go"} {
		assert.False(t, IsGeneratedPath(p), p)
	}
}

func TestIsGeneratedContent(t *testing.T) {
	assert.True(t, IsGeneratedContent([]byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n")))
	assert.True(t, IsGeneratedContent([]byte("package x\n/* auto-generated */\n")))
	assert.True(t, IsGeneratedContent([]byte("# @generated\n")))
	assert.True(t, IsGeneratedContent([]byte("  // Do not modify this file\n")))
	assert.False(t, IsGeneratedContent([]byte("var x = \"DO NOT EDIT\"\n")))
	assert.False(t, IsGeneratedContent([]byte("// regular comment\npackage x\n")))
	assert.False(t, IsGeneratedContent(nil))
	// only the first kilobyte is inspected
	late := make([]byte, 0, 2000)
	for len(late) < 1100 {
		late = append(late, "// filler line of text\n"...)
	}
	late = append(late, "// Code generated by x. DO NOT EDIT.\n"...)
	assert.False(t, IsGeneratedContent(late))
}
